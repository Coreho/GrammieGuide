import { describe, expect, it } from 'vitest'
import { isPublicAddress } from '../../src/main/services/news/publicAddress'

describe('isPublicAddress', () => {
  it.each([
    '0.1.2.3',
    '10.0.0.1',
    '127.0.0.1',
    '127.255.255.254',
    '100.64.0.0',
    '100.127.255.255',
    '169.254.1.1',
    '172.16.0.0',
    '172.31.255.255',
    '192.168.0.1',
    '192.0.0.8',
    '192.0.2.1',
    '192.88.99.1',
    '198.18.0.1',
    '198.19.255.255',
    '198.51.100.1',
    '203.0.113.1',
    '224.0.0.1',
    '239.255.255.255',
    '240.0.0.1',
    '255.255.255.255',
    '::',
    '::1',
    '::127.0.0.1',
    'fc00::1',
    'fdff::1',
    'fe80::1',
    'febf::1',
    'fec0::1',
    'ff02::1',
    'fe80::1%eth0',
    '::ffff:127.0.0.1',
    '::ffff:10.0.0.1',
    '::ffff:172.16.0.1',
    '::ffff:192.168.1.1',
    '::ffff:169.254.1.1',
    '::ffff:100.64.0.1',
    '::ffff:0.0.0.0',
    '::ffff:224.0.0.1',
    '::ffff:7f00:1',
    '0:0:0:0:0:FFFF:c0a8:101',
    '64:ff9b::7f00:1',
    '100::1',
    '2001::1',
    '2001:2::1',
    '2001:db8::1',
    '2002:7f00:1::',
    '3fff::1',
    '',
    'localhost',
    '1.2.3',
    '256.1.1.1',
    '[::1]',
    'not-an-ip'
  ])('rejects non-public or invalid address %s', (address) => {
    expect(isPublicAddress(address)).toBe(false)
  })

  it.each([
    '1.1.1.1',
    '8.8.8.8',
    '100.63.255.255',
    '100.128.0.0',
    '172.15.255.255',
    '172.32.0.0',
    '169.253.255.255',
    '192.169.0.1',
    '198.17.255.255',
    '198.20.0.0',
    '223.255.255.255',
    '2606:4700:4700::1111',
    '2001:4860:4860::8888',
    '::ffff:8.8.8.8',
    '::ffff:808:808',
    '0:0:0:0:0:ffff:808:808'
  ])('accepts public address %s', (address) => {
    expect(isPublicAddress(address)).toBe(true)
  })
})
